/** 一句话版免责声明：CLI 启动横幅、通知栏这类放不下长文的地方用。 */
export function shortDisclaimer(): string {
  return `${PROJECT} 仅供学习研究，按「现状」提供，作者不承担任何责任；注入微信客户端可能导致账号被封禁`;
}

/** 完整纯文本版：CLI 子命令、Release 说明、纯文本导出用。 */
export function disclaimerText(options: { width?: number } = {}): string {
  const width = options.width ?? 78;
  const rule = '═'.repeat(width);
  const lines: string[] = [];

  lines.push(rule);
  lines.push(`  ${PROJECT} · 免责声明与风险提示（${RISK_LEVEL.label}）`);
  lines.push(rule);
  lines.push('');
  lines.push(`〔风险提示〕${RISK_LEVEL.summary}`);
  lines.push('');
  for (const item of RISK_NOTICE) lines.push(`  ! ${item}`);
  lines.push('');
  for (const section of DISCLAIMER_SECTIONS) {
    lines.push(`〔${section.title}〕`);
    for (const item of section.items) lines.push(`  · ${item}`);
    lines.push('');
  }
  lines.push('  以上为完整声明。若你不同意其中任何一条，请立即停止使用并删除本项目。');
  lines.push(rule);
  return lines.join('\n');
}

